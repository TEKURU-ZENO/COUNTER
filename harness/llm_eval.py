"""
LLM evaluation: the real tool-calling agent, driven by an LLM-simulated caller.

Payments run against the deterministic mock gateway (a simulated buyer approves every link), so
this isolates the model's behaviour: did it build the right order, call tools validly, ask when
unsure, and resist manipulation? Adversarial callers are generated by an attacker LLM; success
for them is judged on the ledger, never on the transcript.

    python -m harness.llm_eval --agents anthropic:claude-haiku-5-5,anthropic:claude-sonnet-5-5 \
        --simulator anthropic:claude-haiku-5-5 --seeds 3 \
        --price claude-haiku-5-5=1.0,5.0 --price claude-sonnet-5-5=3.0,15.0

--price takes USD per million input,output tokens. Without it, cost is reported as tokens only
(this script does not guess prices).
"""

